"""FFmpeg render plan for vertical short-form clips.

Reframing is a centred 9:16 crop from the largest 9:16 window in the source.
The output is scaled to OUTPUT_WIDTH x OUTPUT_HEIGHT only when the source is
tall enough; smaller sources are never upscaled. Audio is loudness-normalised
and captions are burned in from an ASS file generated by the captions package.
"""
from __future__ import annotations
import re
import shutil
import tempfile

import logging
import math
import os
from dataclasses import dataclass
from typing import Dict, List, Optional, Tuple

from ..config import settings
from ..errors import MediaValidationError, PipelineError
from .ffmpeg import ffmpeg
from .probe import MediaInfo, probe, verify_decodable

logger = logging.getLogger("studio.render")
TARGET_RATIO = 9 / 16
MIN_HEIGHT_FOR_TARGET = 720  # below this, output keeps the source crop size (no upscaling)
LOUDNORM = "loudnorm=I=-16:TP=-1.5:LRA=11"


def _even(n: float) -> int:
    value = int(math.floor(n))
    return value - (value % 2)


@dataclass(frozen=True)
class Geometry:
    src_w: int
    src_h: int
    crop_w: int
    crop_h: int
    out_w: int
    out_h: int


def crop_geometry(src_w: int, src_h: int, out_w: int, out_h: int) -> Geometry:
    if src_w <= 0 or src_h <= 0:
        raise PipelineError("invalid_dimensions", "Source dimensions are invalid.")
    if src_w / src_h >= TARGET_RATIO:  # wider than 9:16: keep full height, crop the sides
        crop_h = _even(src_h)
        crop_w = _even(src_h * TARGET_RATIO)
    else:  # narrower than 9:16: keep full width, crop top and bottom
        crop_w = _even(src_w)
        crop_h = _even(src_w / TARGET_RATIO)
    crop_w, crop_h = max(2, min(crop_w, _even(src_w))), max(2, min(crop_h, _even(src_h)))
    if crop_h >= MIN_HEIGHT_FOR_TARGET:
        # Crop is exactly 9:16, so scaling to the target keeps the aspect ratio.
        scale_w, scale_h = out_w, out_h
    else:
        # Very small sources keep their own resolution rather than being blown up.
        scale_w, scale_h = crop_w, crop_h
    return Geometry(src_w, src_h, crop_w, crop_h, scale_w, scale_h)


def _escape_filter_value(value: str) -> str:
    for ch in ("\\", ":", "'", ",", "[", "]", ";"):
        value = value.replace(ch, "\\" + ch)
    return value


def video_filter(geom: Geometry, ass_path: Optional[str]) -> str:
    parts = [
        f"crop={geom.crop_w}:{geom.crop_h}:(iw-{geom.crop_w})/2:(ih-{geom.crop_h})/2",
        f"scale={geom.out_w}:{geom.out_h}:flags=lanczos",
        "setsar=1",
    ]
    if ass_path:
        parts.append("ass=filename=" + _escape_filter_value(ass_path))
    return ",".join(parts)


def clip_args(*, source: str, start: float, duration: float, geom: Geometry, out_path: str,
              has_audio: bool, ass_path: Optional[str]) -> List[str]:
    args = [
        "-ss", f"{start:.3f}", "-i", source, "-t", f"{duration:.3f}",
        "-map", "0:v:0", "-vf", video_filter(geom, ass_path),
    ]
    if has_audio:
        args += ["-map", "0:a:0", "-af", LOUDNORM, "-c:a", "aac", "-b:a", "160k", "-ac", "2", "-ar", "48000"]
    else:
        args += ["-an"]
    args += [
        "-c:v", "libx264", "-preset", "veryfast", "-crf", "21", "-profile:v", "high",
        "-pix_fmt", "yuv420p", "-movflags", "+faststart",
    ]
    if settings.FFMPEG_THREADS:
        args += ["-threads", str(settings.FFMPEG_THREADS)]
    args += ["-y", out_path]
    return args


_SAFE_FILTER_PATH = re.compile(r"^[A-Za-z0-9_./-]+$")


def _stage_captions(ass_path: str) -> Tuple[str, str]:
    """Copy captions to a fixed, filter-safe name. FFmpeg's filter parser mangles paths with quotes,
    brackets or commas, so the burn-in never receives the caller's path directly."""
    workdir = tempfile.mkdtemp(prefix="ass-")
    dest = os.path.join(workdir, "captions.ass")
    shutil.copyfile(ass_path, dest)
    if not _SAFE_FILTER_PATH.match(dest):
        shutil.rmtree(workdir, ignore_errors=True)
        raise PipelineError("ffmpeg_render_failed", "Temporary caption path is not usable.", retryable=True)
    return dest, workdir


def render_clip(*, source: str, start: float, end: float, out_path: str, src: MediaInfo,
                ass_path: Optional[str], cancel_check=None) -> Geometry:
    if not ass_path:
        return _render(source=source, start=start, end=end, out_path=out_path, src=src, ass_path=None,
                       cancel_check=cancel_check)
    staged, workdir = _stage_captions(ass_path)
    try:
        return _render(source=source, start=start, end=end, out_path=out_path, src=src, ass_path=staged,
                       cancel_check=cancel_check)
    finally:
        shutil.rmtree(workdir, ignore_errors=True)


def _render(*, source: str, start: float, end: float, out_path: str, src: MediaInfo,
            ass_path: Optional[str], cancel_check=None) -> Geometry:
    geom = crop_geometry(src.width, src.height, settings.OUTPUT_WIDTH, settings.OUTPUT_HEIGHT)
    duration = end - start
    args = clip_args(source=source, start=start, duration=duration, geom=geom, out_path=out_path,
                     has_audio=src.has_audio, ass_path=ass_path)
    result = ffmpeg(args, timeout=settings.FFMPEG_TIMEOUT_SECONDS, cancel_check=cancel_check, label="render_clip")
    if result.returncode != 0 or not os.path.isfile(out_path) or os.path.getsize(out_path) == 0:
        raise PipelineError("ffmpeg_render_failed", "A clip could not be rendered from this source.", retryable=True)
    return geom


def thumbnail(video: str, out_jpg: str, at_seconds: float) -> None:
    result = ffmpeg(
        ["-ss", f"{max(0.0, at_seconds):.3f}", "-i", video, "-frames:v", "1", "-vf", "scale=540:-2", "-y", out_jpg],
        timeout=120, label="thumbnail",
    )
    if result.returncode != 0 or not os.path.isfile(out_jpg):
        raise PipelineError("thumbnail_failed", "The clip thumbnail could not be generated.", retryable=True)


def validate_output(path: str, *, expect_w: int, expect_h: int, expect_duration: float,
                    expect_audio: bool) -> Dict:
    """Confirm a rendered MP4 is playable and matches its plan. Raises MediaValidationError on any mismatch."""
    info = probe(path)
    problems: List[str] = []
    if info.video_codec != "h264":
        problems.append(f"video codec is {info.video_codec}, expected h264")
    if (info.width, info.height) != (expect_w, expect_h):
        problems.append(f"dimensions are {info.width}x{info.height}, expected {expect_w}x{expect_h}")
    if abs(info.duration - expect_duration) > max(0.35, expect_duration * 0.02):
        problems.append(f"duration is {info.duration:.2f}s, expected {expect_duration:.2f}s")
    if expect_audio and not info.has_audio:
        problems.append("audio stream is missing")
    if not expect_audio and info.has_audio:
        problems.append("unexpected audio stream")
    if "mp4" not in info.format_name and "mov" not in info.format_name:
        problems.append(f"container is {info.format_name}, expected MP4")
    if problems:
        raise MediaValidationError("Rendered clip failed validation: " + "; ".join(problems),
                                   code="output_validation_failed")
    verify_decodable(path, timeout=300)
    return {
        "width": info.width, "height": info.height, "duration": info.duration,
        "video_codec": info.video_codec, "audio_codec": info.audio_codec, "has_audio": info.has_audio,
        "container": info.format_name, "size_bytes": os.path.getsize(path), "decodable": True,
    }


def source_geometry_for_preview(info: MediaInfo) -> Tuple[int, int]:
    return info.width, info.height
